package com.mrleonardos.codeutils.api.restart;

/**
 * Точка остановки, в которой мод зовёт чужие шаги.
 *
 * <p>
 * Точки стоят там, где состояние сервера меняется необратимо. До закрытия двери игроки ещё заходят, до
 * кика они ещё в мире, между киком и записью мир уже пуст, а после записи файлы на диске окончательные.
 */
public enum RestartPhase {

    /** Вход ещё открыт, игроки на месте. Годится для объявления своим способом. */
    BEFORE_DOOR,

    /** Дверь закрыта, игроки ещё в мире. Последняя точка, где их можно потрогать. */
    BEFORE_KICK,

    /** Игроков нет, файлы ещё не записаны. Сюда пишут своё состояние из памяти. */
    BEFORE_SAVE,

    /** Файлы игроков и миров записаны. Сюда снимают снимок готовых файлов. */
    AFTER_SAVE
}

package com.mrleonardos.codeutils.api.restart;

/**
 * Шаг чужого мода в остановке сервера.
 *
 * <p>
 * Мод, который держит своё состояние в памяти, пишет его в {@link RestartPhase#BEFORE_SAVE}; мод,
 * которому нужен снимок готовых файлов, работает в {@link RestartPhase#AFTER_SAVE}. Имя шага уходит в лог
 * до его запуска: прервать зависший шаг в главном потоке нельзя, зато видно, кто именно завис.
 *
 * <p>
 * Упавший шаг записывается в лог и остановку не отменяет. Сервер, который не остановился из-за чужого
 * исключения, хуже сервера, остановленного с жалобой в логе.
 */
public interface RestartStep {

    /** В какой точке остановки звать шаг. */
    RestartPhase phase();

    /** Имя шага для строки в логе. */
    String name();

    /** Сделать своё. Вызов идёт в главном потоке сервера. */
    void run(RestartPlanView plan);
}

package com.mrleonardos.codeutils.api.run;

/**
 * Чем выполняется команда задания.
 *
 * <p>
 * Встроен один исполнитель, {@code server}: он отдаёт строку менеджеру команд сервера. Свой исполнитель
 * нужен тому, кто хочет выполнять задание не игровой командой, а по-своему: дёрнуть свой api, сходить в
 * очередь, разложить работу по нескольким шагам.
 *
 * <p>
 * Вызов идёт в главном потоке сервера, поэтому исполнителю можно трогать мир. Долгую работу он обязан
 * увести в свой поток и ответить сразу.
 */
@FunctionalInterface
public interface CommandRunner {

    /** Выполнить заявку и сказать, чем кончилось. */
    RunOutcome run(CommandTicket ticket);
}

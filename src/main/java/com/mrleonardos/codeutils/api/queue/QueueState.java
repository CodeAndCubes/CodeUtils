package com.mrleonardos.codeutils.api.queue;

import java.util.List;
import java.util.Optional;
import java.util.UUID;

/**
 * Что известно о слотах в момент стука: онлайн, ступени, очередь и придержанный слот.
 *
 * <p>
 * Числа собраны заранее и мира не касаются: решение принимается на потоке сети, где обращение к списку
 * игроков сервера или к миру даёт гонку. Онлайн мод считает своим счётчиком, который двигают события
 * входа и выхода в главном потоке.
 */
public interface QueueState {

    /** Сколько игроков сейчас на сервере. */
    int online();

    /** Потолок для игрока без ступени. */
    int baseSlots();

    /** Имена ступеней от старшей к младшей: старшинство задаёт число слотов. */
    List<String> tiers();

    /** Потолок названной ступени; ноль, если такой ступени нет. */
    int slotsOf(String tier);

    /** Узел права названной ступени; пустая строка, если такой ступени нет. */
    String nodeOf(String tier);

    /** Есть ли у игрока узел права. Вопрос уходит в {@code PermissionService} ядра. */
    boolean allowed(UUID player, String node);

    /** Ведётся ли очередь: при {@code queue.enabled = false} отказ уходит без номера. */
    boolean queueOn();

    /** Очередь по порядку обслуживания. */
    List<QueueTicket> queue();

    /**
     * Билет, за которым придержан освободившийся слот.
     *
     * <p>
     * Слот держится за головой очереди {@code holdSeconds}. Пока он придержан, любой другой игрок
     * получает отказ, даже когда по числам место есть. Пустой ответ означает, что придерживать нечего.
     */
    Optional<QueueTicket> heldFor();
}

package com.mrleonardos.codeutils.api.queue;

/**
 * Кого пускать, когда слоты кончаются.
 *
 * <p>
 * Встроена одна политика, {@code by-permission}: ступень игрока определяется узлом права из
 * {@code utils-queue.toml}, и онлайн сравнивается с потолком этой ступени. Своя политика нужна тому, кто
 * считает ступень иначе: по своей базе доноров, по времени, проведённому на сервере, по чему угодно
 * своему. Имя политики называет ключ {@code queue.policy}.
 *
 * <p>
 * Вопрос задаётся на потоке сети, а не в главном. Политика обязана отвечать сразу и не трогать мир: всё,
 * что ей нужно, лежит в {@link QueueState}. Поход в свою базу делается заранее и своим потоком, сюда
 * отдаётся готовый ответ.
 */
@FunctionalInterface
public interface QueuePolicy {

    /** Пустить или отказать. */
    QueueDecision decide(QueueRequest request, QueueState state);
}

package com.mrleonardos.codeutils.api.when;

/**
 * Чужое условие запуска: «только когда идёт ивент», «только когда база отвечает».
 *
 * <p>
 * Мод заявляет условие под своим именем в фазе init, админ называет это имя в списке {@code custom}
 * блока {@code when}. Имя, которого в реестре нет, названо в логе один раз при старте и считается
 * невыполненным условием: расписание с опечаткой молчит, а не срабатывает мимо задуманного.
 *
 * <p>
 * Условие спрашивают на каждом такте в главном потоке сервера, поэтому оно обязано отвечать сразу.
 * Хождение в базу или в сеть делается своим потоком, а сюда отдаётся уже готовый ответ.
 */
@FunctionalInterface
public interface RunCondition {

    /** Разрешает ли условие сработать прямо сейчас. */
    boolean allows(ServerSnapshot snapshot);
}

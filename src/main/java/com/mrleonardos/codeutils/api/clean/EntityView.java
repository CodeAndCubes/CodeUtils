package com.mrleonardos.codeutils.api.clean;

import java.util.UUID;

/**
 * Сущность глазами очистки: тип, место, возраст и признаки, по которым её защищают.
 *
 * <p>
 * Самой сущности здесь нет и не будет: типов игры в api линейки не держит ни один мод. Свою сущность
 * чужой мод узнаёт по {@link #type()}, потому что там стоит то самое имя, под которым он её
 * зарегистрировал. Предел границы назван прямо: защитить сущность по её внутреннему состоянию через этот
 * шов нельзя, для этого у мода есть свой код.
 */
public interface EntityView {

    /** Возраст неизвестен моду от игры: считать его придётся от первой встречи. */
    int AGE_UNKNOWN = -1;

    /** Имя типа, как его зарегистрировала игра: {@code Item}, {@code Zombie}, {@code Thermal...}. */
    String type();

    /** Род, по которому работают группы с собачкой. */
    EntityKind kind();

    /** Кто это, для отметки о первой встрече и для строки в логе. */
    UUID id();

    /** Номер измерения. */
    int dimension();

    /** Номер чанка по оси X: по нему считается порог {@code chunkThreshold}. */
    int chunkX();

    /** Номер чанка по оси Z. */
    int chunkZ();

    /**
     * Возраст в секундах или {@link #AGE_UNKNOWN}.
     *
     * <p>
     * У брошенного предмета и у шарика опыта возраст считает сама игра, у остальных сущностей он равен
     * времени с загрузки сущности в мир: игра обнуляет свой счётчик тиков, когда сущность приходит из
     * файла, поэтому для мода она рождается в момент загрузки.
     *
     * <p>
     * {@link #AGE_UNKNOWN} означает, что возраста нет вовсе. Правило с ненулевым {@code minAgeSeconds}
     * такую сущность не трогает: неизвестный возраст читается как «слишком молода», а не как «сойдёт».
     */
    int ageSeconds();

    /** Висит бирка с именем. */
    boolean named();

    /** Прирученное или чьё-то. */
    boolean tamed();

    /** На поводке. */
    boolean leashed();

    /** Босс. */
    boolean boss();

    /** Помечено вечным и само не исчезает. */
    boolean persistent();

    /** Транспорт или животное с непустым содержимым. */
    boolean carrying();

    /** На нём кто-то едет. */
    boolean ridden();

    /** Картина, рамка или другая висящая сущность. */
    boolean hanging();
}

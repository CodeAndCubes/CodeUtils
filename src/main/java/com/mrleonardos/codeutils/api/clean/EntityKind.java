package com.mrleonardos.codeutils.api.clean;

/**
 * Род сущности: по нему работают группы с собачкой в ключе {@code types} правила очистки.
 *
 * <p>
 * Род один на сущность, поэтому у лодки он {@link #VEHICLE}, а не {@link #OTHER}, а у прирученного волка
 * {@link #PASSIVE}. Всё, чего мод не отнёс ни к одной группе, получает {@link #OTHER}: такая сущность
 * попадает под правило только точным именем или звёздочкой.
 *
 * <p>
 * Игрок вынесен отдельным родом, потому что очистка не удаляет игроков вовсе: это не настройка и не
 * защита, которую можно снять.
 */
public enum EntityKind {

    /** Игрок. Очистка его не трогает никогда. */
    PLAYER,

    /** Брошенный предмет, группа {@code @item}. */
    ITEM,

    /** Шарик опыта, группа {@code @xp}. */
    XP,

    /** Враждебный моб, группа {@code @hostile}. */
    HOSTILE,

    /** Мирная живность, группа {@code @passive}. */
    PASSIVE,

    /** Стрела, снежок и прочее летящее, группа {@code @projectile}. */
    PROJECTILE,

    /** Вагонетка и лодка, группа {@code @vehicle}. */
    VEHICLE,

    /** Всё остальное: рамки, картины, сущности чужих модов без своей группы. */
    OTHER
}

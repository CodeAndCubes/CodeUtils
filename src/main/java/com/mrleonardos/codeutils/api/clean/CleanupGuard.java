package com.mrleonardos.codeutils.api.clean;

/**
 * Защита сущности от очистки.
 *
 * <p>
 * Восемь защит встроены: бирка с именем, приручение, поводок, босс, вечная метка, непустое содержимое,
 * наездник и висящая сущность. Свою защиту мод заявляет в реестр в фазе init под своим именем, и её
 * спрашивают при каждом проходе, а не только когда её назвали в файле настроек.
 *
 * <p>
 * Снять защиту админ может только явно, назвав её имя в {@code ignoreGuards} конкретного правила. Это
 * работает и для встроенных защит, и для защит чужих модов, чтобы владелец сервера не оказался запертым.
 *
 * <p>
 * Вопрос задаётся в главном потоке на каждую подходящую сущность прохода, поэтому ответ обязан быть
 * быстрым: чтение своих полей, а не поход в базу.
 */
@FunctionalInterface
public interface CleanupGuard {

    /** Защищена ли сущность от снятия. */
    boolean protects(EntityView entity);
}
